#!/usr/bin/env python3
# Writes shim/src/stubs/xg_stubs.c: a definition for every symbol in out/kpi-todo.txt, so the kext links before the
# shim is complete. A function stub panics with its name; a symbol FreeBSD or LinuxKPI declares as a variable gets a
# zeroed, aligned block instead. The panic message names the next function to write.
import os, re, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.expanduser("~/src/xe-src")
HDRS = [os.path.join(SRC, "freebsd/sys/sys"), os.path.join(SRC, "freebsd/sys/vm"), os.path.join(SRC, "freebsd/sys/amd64/include"),
        os.path.join(SRC, "freebsd/sys/x86/include"), os.path.join(SRC, "freebsd/sys/compat/linuxkpi/common/include"),
        os.path.join(SRC, "drm-kmod/linuxkpi"), os.path.join(SRC, "drm-kmod/drivers/gpu/drm"), os.path.join(SRC, "freebsd/sys/dev/pci")]


def is_variable(name):
    pat = rf"^\s*extern\b[^(;]*\b{re.escape(name)}\s*(\[[^\]]*\])*\s*(__\w+(\([^)]*\))?\s*)*;"
    r = subprocess.run(["grep", "-rhE", "--include=*.h", f"\\b{name}\\b"] + HDRS, capture_output=True, text=True)
    for line in r.stdout.splitlines():
        if re.search(pat, line) and "(" not in line.split(name)[0]:
            return True
    # sysctl nodes and malloc types are objects too
    return name.startswith(("sysctl__", "M_")) or name in ("Giant", "main_vd", "pagertab", "pageproc")


def main():
    syms = [l.split()[1] for l in open(os.path.join(ROOT, "out/kpi-todo.txt"))]
    out = ["/* generated by tools/stubs.py: placeholders for the FreeBSD kernel API not written yet */",
           "extern void xg_unimpl(const char *name) __attribute__((__noreturn__));", ""]
    nv = nf = 0
    for s in sorted(syms):
        name = s[1:] if s.startswith("_") else s
        if name.startswith("xg_"):
            continue
        if is_variable(name):
            out.append(f"char {name}[4096] __attribute__((aligned(64)));")
            nv += 1
        else:
            out.append(f"void {name}(void) {{ xg_unimpl(\"{name}\"); }}")
            nf += 1
    d = os.path.join(ROOT, "shim/src/stubs")
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "xg_stubs.c"), "w").write("\n".join(out) + "\n")
    print(f"stubs: {nf} functions, {nv} variables")


if __name__ == "__main__":
    main()
